// nullish coalescing Operator

const user_age = null

let result = user_age ?? "Age not provided";

console.log(result)



const user_age2 = 0

let result2 = user_age2 ?? "Age not provided";

console.log(result2)


// falsy Operator

const user_age3 = 0

let result3 = user_age3 || "Age not provided";

console.log(result3)
